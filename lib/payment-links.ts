import paymentLinksData from './payment-links.json';
import { PRICING, type Recurrence, type ServiceKey, type ServiceOffer } from './pricing';

export interface PaymentLinkEntry {
    productId: string;
    priceId: string;
    paymentLinkId: string;
    url: string;
    amount: number;
    recurrence: Recurrence;
    /**
     * Legacy. Links created before the free trial was dropped carry a number
     * here; a link with one is stale by definition (see `isCurrent`).
     */
    trialDays?: number | null;
    mode: 'test' | 'live';
    updatedAt: string;
}

const LEDGER = paymentLinksData as Partial<Record<string, PaymentLinkEntry>>;

/**
 * Whether a ledger entry still charges what the offer publishes.
 *
 * The ledger is written by a script that needs a Stripe key, so it can lag
 * behind `PRICING`. When it does, the link must not be shown: it would send a
 * visitor to pay the OLD price for a plan advertised at the new one.
 *
 * A floor price never qualifies. "From 20000" is where quotes start, not an
 * amount anyone can be charged through a fixed link.
 */
export function isCurrent(entry: PaymentLinkEntry | undefined, offer: ServiceOffer): boolean {
    if (!entry?.url) return false;
    if (offer.base.from) return false;
    return (
        entry.amount === offer.base.amount &&
        entry.recurrence === offer.base.recurrence &&
        !entry.trialDays
    );
}

/**
 * The Payment Link URL for a service, generated by
 * `scripts/create-payment-links.mjs` from `lib/pricing.ts`.
 *
 * `undefined` whenever there is nothing safe to link to: no entry yet, an entry
 * created for a previous price, or a service priced as a floor. Callers render
 * the "pay online" button only when this returns a URL, so a stale ledger hides
 * the button instead of mischarging. Rerun the sync script to bring it back.
 */
export function paymentLinkUrl(key: ServiceKey): string | undefined {
    const entry = LEDGER[key];
    return isCurrent(entry, PRICING[key]) ? entry?.url : undefined;
}
